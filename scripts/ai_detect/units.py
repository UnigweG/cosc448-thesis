"""Split a repository snapshot into units that a detector can score.

A unit is a function (Python, via the ast module) or a window of consecutive lines
(every other language, and Python code outside functions). Detectors in the literature
are trained and evaluated on function- or snippet-sized inputs (DetectCodeGPT trims to
128 tokens; DroidDetect and GPTSniffer score snippets up to ~512 tokens), so whole files
would be out of distribution.

Files are read from git at the snapshot commit (`git show <sha>:<path>`), never from the
working tree, so the result is the same however the clone is checked out.
"""
import ast
import hashlib
import re
import subprocess
from dataclasses import asdict, dataclass

EXT_LANG = {
    ".py": "python", ".js": "javascript", ".jsx": "javascript", ".mjs": "javascript",
    ".ts": "typescript", ".tsx": "typescript", ".java": "java", ".cs": "csharp",
    ".go": "go", ".cpp": "cpp", ".cc": "cpp", ".c": "c", ".h": "c", ".hpp": "cpp",
    ".dart": "dart", ".kt": "kotlin", ".swift": "swift", ".rb": "ruby", ".php": "php",
    ".rs": "rust",
}
# same exclusions as the SonarQube scan, plus generated and lock files
SKIP_PATH = re.compile(
    r"(^|/)(node_modules|\.venv|venv|site-packages|dist|build|target|__pycache__|vendor|"
    r"\.next|coverage|migrations|bower_components|third_party)/"
    r"|\.min\.(js|css)$|(^|/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml)$"
    r"|_pb2(_grpc)?\.py$|\.d\.ts$|\.g\.dart$|\.designer\.cs$")
TEST_PATH = re.compile(r"(^|/)(tests?|__tests__|spec)/|(^|/)test_[^/]*$|_test\.[a-z]+$|\.(test|spec)\.[jt]sx?$")
GENERATED_MARK = re.compile(r"(auto-?generated|do not edit|@generated|generated by)", re.I)


@dataclass
class Unit:
    unit_id: str
    path: str
    language: str
    kind: str          # "function" or "window"
    start: int         # 1-based, inclusive
    end: int
    sloc: int          # non-blank lines
    is_test: bool
    text: str

    def as_row(self, **extra):
        return {**asdict(self), **extra}


def _git(path, *args):
    return subprocess.run(["git", "-C", str(path), *args], capture_output=True, text=True,
                          errors="replace").stdout


def list_files(repo, sha):
    files = _git(repo, "ls-tree", "-r", "--name-only", sha).splitlines()
    out = []
    for f in files:
        ext = "." + f.rsplit(".", 1)[-1].lower() if "." in f.rsplit("/", 1)[-1] else ""
        if ext in EXT_LANG and not SKIP_PATH.search(f):
            out.append((f, EXT_LANG[ext]))
    return out


def _sloc(lines):
    return sum(1 for l in lines if l.strip())


def _uid(path, start, end, text):
    h = hashlib.sha1(f"{path}:{start}:{end}:{text}".encode()).hexdigest()[:16]
    return h


def python_units(path, text, min_sloc=5, max_lines=200):
    """Top-level and nested functions (and methods); one unit each, decorators included.

    Lines not covered by any function are grouped into windows by `window_units`."""
    lines = text.splitlines()
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return [], list(range(1, len(lines) + 1))
    spans = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            start = min([node.lineno] + [d.lineno for d in node.decorator_list])
            spans.append((start, node.end_lineno))
    # keep outermost spans only; methods are kept, nested inner functions are folded in
    spans.sort()
    kept = []
    for s, e in spans:
        if kept and s >= kept[-1][0] and e <= kept[-1][1]:
            continue
        kept.append((s, e))
    units, covered = [], set()
    for s, e in kept:
        body = lines[s - 1:e]
        covered.update(range(s, e + 1))
        if _sloc(body) < min_sloc:
            continue
        for ws in range(s, e + 1, max_lines):  # very long functions are split
            we = min(e, ws + max_lines - 1)
            chunk = "\n".join(lines[ws - 1:we])
            units.append(("function", ws, we, chunk))
    rest = [i for i in range(1, len(lines) + 1) if i not in covered]
    return units, rest


_FUNC_DECL = {"function_declaration", "generator_function_declaration", "method_definition"}
_FUNC_VALUE = {"arrow_function", "function_expression", "function", "generator_function"}
_BINDERS = {"variable_declarator", "public_field_definition", "pair", "assignment_expression", "field_definition"}
_PARSERS = {}


def _js_parser(path, language):
    """tree-sitter parser for a JavaScript, TypeScript or TSX file (cached)."""
    key = "tsx" if path.lower().endswith(".tsx") else language
    if key not in _PARSERS:
        from tree_sitter import Language, Parser
        if key == "javascript":
            import tree_sitter_javascript as g
            lang = g.language()
        else:
            import tree_sitter_typescript as g
            lang = g.language_tsx() if key == "tsx" else g.language_typescript()
        _PARSERS[key] = Parser(Language(lang))
    return _PARSERS[key]


def _outer(node):
    """The declaration or export statement that carries the node (so `export const f = () => ...` is whole)."""
    while node.parent is not None and node.parent.type in ("lexical_declaration", "variable_declaration", "export_statement"):
        node = node.parent
    return node


def js_units(path, language, text, min_sloc=5, max_lines=200):
    """Whole functions of a JavaScript/TypeScript file: declarations, methods and arrow/function expressions bound to a name.

    Outermost only (a callback inside a function is part of it). Returns (units, uncovered line numbers) like
    `python_units`, with the same min size and chunking of very long functions."""
    lines = text.splitlines()
    tree = _js_parser(path, language).parse(text.encode("utf-8", "replace"))
    spans = []

    def visit(node):
        if node.type in _FUNC_DECL:
            n = _outer(node)
            spans.append((n.start_point[0] + 1, n.end_point[0] + 1))
            return
        if node.type in _BINDERS:
            value = node.child_by_field_name("value") or node.child_by_field_name("right")
            if value is not None and value.type in _FUNC_VALUE:
                n = _outer(node)
                spans.append((n.start_point[0] + 1, n.end_point[0] + 1))
                return
        for c in node.children:
            visit(c)

    visit(tree.root_node)
    spans = sorted(set(spans))
    kept = []
    for s, e in spans:
        if kept and s >= kept[-1][0] and e <= kept[-1][1]:
            continue
        kept.append((s, e))
    units, covered = [], set()
    for s, e in kept:
        covered.update(range(s, e + 1))
        if _sloc(lines[s - 1:e]) < min_sloc:
            continue
        for ws in range(s, e + 1, max_lines):
            we = min(e, ws + max_lines - 1)
            units.append(("function", ws, we, "\n".join(lines[ws - 1:we])))
    return units, [i for i in range(1, len(lines) + 1) if i not in covered]


def window_units(lines, line_numbers, window=40, min_sloc=8):
    """Group the given line numbers into windows of up to `window` consecutive lines."""
    units, run = [], []

    def flush():
        if run:
            body = [lines[i - 1] for i in run]
            if _sloc(body) >= min_sloc:
                units.append(("window", run[0], run[-1], "\n".join(body)))

    for i in line_numbers:
        if run and (i != run[-1] + 1 or len(run) >= window):
            flush()
            run = []
        run.append(i)
    flush()
    return units


def file_units(path, language, text, window=40):
    if GENERATED_MARK.search(text[:500]):
        return []
    lines = text.splitlines()
    if language == "python":
        fn, rest = python_units(path, text)
        raw = fn + window_units(lines, rest, window)
    elif language in ("javascript", "typescript"):
        fn, rest = js_units(path, language, text)
        raw = fn + window_units(lines, rest, window)
    else:
        raw = window_units(lines, range(1, len(lines) + 1), window)
    is_test = bool(TEST_PATH.search(path))
    return [Unit(_uid(path, s, e, t), path, language, k, s, e, _sloc(t.splitlines()), is_test, t)
            for k, s, e, t in raw]


def repo_units(repo, sha, languages=None, max_file_bytes=200_000, window=40):
    """All units of a repository at commit `sha`."""
    out = []
    for path, lang in list_files(repo, sha):
        if languages and lang not in languages:
            continue
        text = _git(repo, "show", f"{sha}:{path}")
        if not text or len(text) > max_file_bytes or "\0" in text:
            continue
        # minified or data-like files: very long average line
        lines = text.splitlines() or [""]
        if sum(map(len, lines)) / len(lines) > 200:
            continue
        out += file_units(path, lang, text, window)
    return out
